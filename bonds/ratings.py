def get_rating(bond_name: str) -> str:
    """
    Получить кредитный рейтинг по названию облигации.

    Ищет совпадение по части названия (эмитенту) без учёта регистра.

    :param bond_name: название облигации из API
    :return: рейтинг, '-' (если не задан) или 'не найден' (если эмитента нет в словаре)
    """
    name_lower = bond_name.lower()

    for key, rating_value in RATINGS.items():
        if key in name_lower:
            return rating_value

    return 'не найден'
